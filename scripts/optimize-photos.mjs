/**
 * Generate responsive WebP derivatives for the curated project photos and
 * write a typed manifest (src/assets/photos.ts).
 *
 * Sources live in src/assets/photos/<name>-<width>.webp (committed). For each
 * source we emit 480 / 900 / <=1400px variants with the same base name, then
 * build `photos[name] = { src, srcSet, width, height }` so components can render
 * a real <img srcSet> and let the browser pick — instead of inlining megabytes
 * of base64 into the JS bundle.
 *
 * Usage: node scripts/optimize-photos.mjs   (requires `sharp`, a devDependency)
 */
import { readdir, writeFile, unlink } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "src/assets/photos");
const MANIFEST = path.join(ROOT, "src/assets/photos.ts");
const MAX_WIDTH = 1400;
const STEPS = [480, 900];

const sourceRe = /^(?<name>[a-z]+)-(?<width>\d+)\.webp$/;

async function main() {
  const files = (await readdir(DIR)).filter((f) => sourceRe.test(f));
  const groups = new Map();

  for (const file of files) {
    const { name } = sourceRe.exec(file).groups;
    if (!groups.has(name)) groups.set(name, []);
    groups.get(name).push(file);
  }

  const entries = [];

  for (const [name, members] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    // The widest existing file is the master; if it is larger than MAX_WIDTH it is
    // downscaled and the oversized original is removed from the repository.
    const master = members
      .map((file) => ({ file, width: Number(sourceRe.exec(file).groups.width) }))
      .sort((a, b) => b.width - a.width)[0];

    const target = Math.min(master.width, MAX_WIDTH);
    const widths = [...new Set([...STEPS.filter((w) => w < target), target])];

    for (const width of widths) {
      const out = path.join(DIR, `${name}-${width}.webp`);
      const resized = await sharp(path.join(DIR, master.file))
        .resize({ width, withoutEnlargement: true })
        .webp({ quality: 74, effort: 5 })
        .toBuffer();
      await writeFile(out, resized);
    }

    if (master.width > target) await unlink(path.join(DIR, master.file));

    const largest = path.join(DIR, `${name}-${target}.webp`);
    const { width, height } = await sharp(largest).metadata();

    entries.push({
      name,
      widths,
      width,
      height,
    });
  }

  // Static imports of each variant: Vite hashes and emits these as real,
  // cacheable assets (unlike base64 data URIs, which cannot be lazy or cached).
  const imports = entries.flatMap((e) =>
    e.widths.map((w) => `import ${e.name}${w} from "./photos/${e.name}-${w}.webp";`),
  );

  const body = entries.map((e) => {
    const largest = e.widths[e.widths.length - 1];
    const srcSet = e.widths.map((w) => `\${${e.name}${w}} ${w}w`).join(", ");
    return (
      `  ${e.name}: {\n` +
      `    src: ${e.name}${largest},\n` +
      `    srcSet: \`${srcSet}\`,\n` +
      `    width: ${e.width},\n` +
      `    height: ${e.height},\n` +
      `  },`
    );
  });

  const lines = [
    "// Generated by scripts/optimize-photos.mjs — do not edit by hand.",
    "// Committed WebP derivatives, emitted by Vite as hashed, cacheable assets.",
    "",
    ...imports,
    "",
    "export interface Photo {",
    "  src: string;",
    "  srcSet: string;",
    "  width: number;",
    "  height: number;",
    "}",
    "",
    "export const photos = {",
    ...body,
    "} as const satisfies Record<string, Photo>;",
    "",
    "export type PhotoName = keyof typeof photos;",
    "",
    'export const photoGalleryUrl = "https://powerwashingoahu.com/recentprojects";',
    "",
  ];

  await writeFile(MANIFEST, lines.join("\n"), "utf8");
  console.log(`Wrote ${entries.length} photo entries to ${path.relative(ROOT, MANIFEST)}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
